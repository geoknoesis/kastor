/**
 * Coordinates code generation from ontology models.
 *
 * All files for one request are generated first, checked for (case-insensitive) file-name collisions, and
 * only then written. A request whose files collide with those of an earlier request of the same compilation (two
 * SHACL files with a shape of the same name generated into one package, or a DSL named like a generated type) is
 * reported as a KSP error naming both requests, and none of its files is written. Outputs are registered as *aggregating* over the annotated source files passed in
 * `sources`, so KSP regenerates them whenever those sources change. KSP cannot observe SHACL / JSON-LD files
 * under `src/main/resources`: [OntologyProcessor] warns about every such file unless the build declares them as
 * inputs of the KSP task and sets [OntologyProcessor.RESOURCES_TRACKED_OPTION]. The `com.geoknoesis.kastor.gen`
 * Gradle plugin tracks ontology files as real task inputs and is the recommended path.
 *
 * `sh:in` value sets are exposed as generated enums by interfaces, wrappers and data classes. The instance DSL
 * generated by [generateInstanceDsl] (and by the Gradle plugin) keeps `String` setters for them, validated
 * against the allowed values, because the DSL can be generated without the enums.
 */
public class GenerationCoordinator(
    private val logger: KSPLogger,
    private val codeGenerator: CodeGenerator
) {
    private val instanceDslGenerator = InstanceDslGenerator(logger)
    /** Files written so far (lower-case qualified name) to their qualified name and the request that wrote them. */
    private val fileOwners = HashMap<String, Pair<String, String>>()

    /**
     * Generates interfaces and wrappers from ontology model.
     *
     * @param validationApiAvailable whether the Bean Validation annotations of [validationAnnotations] are on the
     *   compile class path, asked only when the generated code uses them; when they are not, nothing is written
     * @throws InvalidConfigurationException when data classes would collide with interfaces (empty
     *   [dataClassSuffix]), when generated names collide, or when the generated code needs a Bean Validation API
     *   that is not on the class path
     */
    public fun generateFromOntology(
        model: OntologyModel,
        packageName: String,
        generateInterfaces: Boolean,
        generateWrappers: Boolean,
        validationMode: ValidationMode,
        validationAnnotations: ValidationAnnotations,
        externalValidatorClass: String?,
        generateDataClass: Boolean = false,
        dataClassSuffix: String = DEFAULT_DATA_CLASS_SUFFIX,
        dataClassImplementsInterface: Boolean = false,
        nestedMode: NestedMode = NestedMode.INTERFACE,
        generateWriteSupport: Boolean = false,
        sources: List<KSFile> = emptyList(),
        owner: String = "@Rdf ontology request for package '$packageName'",
        at: KSNode? = null,
        validationApiAvailable: () -> Boolean = { true },
    ) {
        GenerationNames.renamedTypeWarnings(model).forEach { logger.warn(it) }
        if (generateDataClass && dataClassSuffix.isBlank() && (generateInterfaces || generateWrappers || dataClassImplementsInterface)) {
            throw InvalidConfigurationException(
                config = "dataClassSuffix",
                reason = "must not be empty when data classes are generated together with interfaces/wrappers in package " +
                    "'$packageName' (the data class and the interface would both be named after the shape); use e.g. " +
                    "\"$DEFAULT_DATA_CLASS_SUFFIX\"",
            )
        }
        if (dataClassImplementsInterface && !generateInterfaces) {
            logger.warn("dataClassImplementsInterface = true but generateInterfaces = false; the interfaces must exist in '$packageName'")
        }

        val enriched = ShaclEnumExtractor(logger).enrich(model)
        GenerationNames.checkCollisions(enriched)
        val files = mutableListOf<FileSpec>()
        files += EnumGenerator(logger).generateEnums(enriched, packageName).values

        if (generateInterfaces) {
            files += InterfaceGenerator(logger, validationAnnotations)
                .generateInterfaces(enriched, packageName, fallbackUnshapedToIri = true).values
        }

        if (generateWrappers) {
            files += OntologyWrapperGenerator(logger, validationMode, externalValidatorClass)
                .generateWrappers(enriched, packageName, fallbackUnshapedToIri = true).values
        }

        if (generateDataClass) {
            val dcGenerator = DataClassGenerator(
                logger = logger,
                suffix = dataClassSuffix,
                nestedMode = nestedMode,
                implementsInterface = dataClassImplementsInterface,
                validationAnnotations = validationAnnotations,
            )
            val writerGen = if (generateWriteSupport) {
                DataClassWriterGenerator(
                    logger = logger,
                    suffix = dataClassSuffix,
                    nestedMode = nestedMode,
                )
            } else null
            val factoryGenerator = DataClassFactoryGenerator(
                logger = logger,
                suffix = dataClassSuffix,
                nestedMode = nestedMode,
                writerGenerator = writerGen,
            )
            files += dcGenerator.generateDataClasses(enriched, packageName, fallbackUnshapedToIri = true).values
            files += factoryGenerator.generateFactories(enriched, packageName, fallbackUnshapedToIri = true).values
        }

        GenerationNames.checkUniqueFiles(files)
        requireValidationApi(validationAnnotations, files, validationApiAvailable)
        if (!claim(files, owner, at)) return
        files.sortedBy { it.name }.forEach { writeFile(it, sources) }
    }

    /**
     * Fails when [files] import annotations of [flavour] that the compile class path lacks: the generated code would
     * not compile, with an "unresolved reference" far from the cause.
     */
    private fun requireValidationApi(flavour: ValidationAnnotations, files: List<FileSpec>, available: () -> Boolean) {
        val pkg = ValidationAnnotationSpecs.constraintsPackage(flavour) ?: return
        if (files.none { "import $pkg." in it.toString() } || available()) return
        val artifact = when (flavour) {
            ValidationAnnotations.JAVAX -> "javax.validation:validation-api:2.0.1.Final"
            else -> "jakarta.validation:jakarta.validation-api:3.1.1"
        }
        throw InvalidConfigurationException(
            config = "validationAnnotations",
            reason = "validationAnnotations = ValidationAnnotations.$flavour generates $pkg annotations " +
                "(@NotNull, @NotEmpty, @Size) but $pkg.NotNull is not on the compile class path. Add the API, " +
                "e.g. dependencies { implementation(\"$artifact\") } (kastor-gen-runtime provides " +
                "jakarta.validation-api at compile time unless it is excluded), or set " +
                "validationAnnotations = ValidationAnnotations.NONE",
        )
    }

    /**
     * Generates instance DSL from ontology model.
     */
    public fun generateInstanceDsl(
        model: OntologyModel,
        dslName: String,
        packageName: String,
        sources: List<KSFile> = emptyList(),
        owner: String = "@Rdf instance DSL request '$dslName' for package '$packageName'",
        at: KSNode? = null,
    ) {
        logger.info("Processing instance DSL generation: $dslName")
        GenerationNames.renamedTypeWarnings(model).forEach { logger.warn(it) }

        val request = InstanceDslRequest(
            dslName = dslName,
            ontologyModel = model,
            packageName = packageName,
            options = DslGenerationOptions()
        )

        val fileSpec = instanceDslGenerator.generate(request)
        if (!claim(listOf(fileSpec), owner, at)) return
        writeFile(fileSpec, sources)

        logger.info("Generated instance DSL: ${fileSpec.name}.kt")
    }

    /**
     * Records [owner] as the writer of [files], unless another request of this compilation already wrote one of them
     * (compared case-insensitively, as `checkUniqueFiles` does within one request): that is reported as a KSP error
     * naming both requests, nothing of this request is written, and `false` is returned. Without this check the
     * second request would fail with a `FileAlreadyExistsException` wrapped in a generic processing error.
     */
    private fun claim(files: List<FileSpec>, owner: String, at: KSNode?): Boolean {
        val clashes = files.mapNotNull { file ->
            val qualified = "${file.packageName}.${file.name}".removePrefix(".")
            fileOwners[qualified.lowercase()]?.let { (first, firstOwner) -> "$qualified.kt (also $first.kt from $firstOwner)" }
        }
        if (clashes.isNotEmpty()) {
            logger.error(
                "kastor-gen: $owner generates files that another request already generated, so none of its files are " +
                    "written: ${clashes.sorted().joinToString("; ")}. Generate the two requests into different " +
                    "packages (packageName), or rename the colliding shapes or DSL.",
                at,
            )
            return false
        }
        files.forEach { file ->
            val qualified = "${file.packageName}.${file.name}".removePrefix(".")
            fileOwners[qualified.lowercase()] = qualified to owner
        }
        return true
    }

    private fun writeFile(fileSpec: FileSpec, sources: List<KSFile>) {
        val packageName = fileSpec.packageName
        val kspFileName = fileSpec.name.removeSuffix(".kt")
        try {
            codeGenerator.createNewFile(
                dependencies = Dependencies(aggregating = true, *sources.distinct().toTypedArray()),
                packageName = packageName,
                fileName = kspFileName
            ).use { file ->
                file.bufferedWriter(StandardCharsets.UTF_8).use { writer ->
                    fileSpec.writeTo(writer)
                }
            }
            logger.info("Generated file: $kspFileName.kt in package $packageName")
        } catch (e: Exception) {
            throw FileGenerationException(
                fileSpec = fileSpec,
                packageName = packageName,
                cause = e
            )
        }
    }

    public companion object {
        /** Default suffix for generated data classes (`Person` → `PersonRecord`). */
        public const val DEFAULT_DATA_CLASS_SUFFIX: String = "Record"
    }
}
